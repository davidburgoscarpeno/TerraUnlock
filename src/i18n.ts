// anadir un idioma nuevo = nuevo diccionario + entrada en LANGS, sin tocar componentes.
export type Lang = 'es' | 'en';
export const LANGS: { id: Lang; label: string }[] = [
    { id: 'es', label: 'Espanol' },
    { id: 'en', label: 'English' },
];
let current: Lang = 'es';
export function setLang(l: Lang) { current = l; try { document.documentElement.lang = l; } catch { /* sin DOM */ } }
export function getLang(): Lang { return current; }
export function detectLang(): Lang {
    try { return (navigator.language || 'es').toLowerCase().startsWith('es') ? 'es' : 'en'; } catch { return 'es'; }
}
export function dateLocale(): string { return current === 'es' ? 'es-ES' : 'en-US'; }
const MONTHS: Record<Lang, string[]> = {
    es: ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'],
    en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
};
export function monthName(i: number): string { return MONTHS[current][i]; }
// numero con separador decimal del idioma: dec(3.1416, 1) -> '3,1' (es) / '3.1' (en)
export function dec(n: number, digits = 1): string { return n.toFixed(digits).replace('.', current === 'es' ? ',' : '.'); }
// rosa de los vientos abreviada (ES: O=Oeste; EN: W=West, etc.)
export function compass8(x: number, y: number): string {
    const i = Math.round(((Math.atan2(y, x) * 180 / Math.PI) + 360) % 360 / 45) % 8;
    return (current === 'es' ? ['N', 'NE', 'E', 'SE', 'S', 'SO', 'O', 'NO'] : ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'])[i];
}

